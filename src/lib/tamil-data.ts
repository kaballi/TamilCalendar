const TA_DIGITS = ["", "௧", "௨", "௩", "௪", "௫", "௬", "௭", "௮", "௯"];
export function toTamilNumeral(n: number): string {
  if (n < 10) return TA_DIGITS[n] ?? "";
  if (n < 20) return "௰" + (TA_DIGITS[n - 10] ?? "");
  return (TA_DIGITS[Math.floor(n / 10)] ?? "") + "௰" + (TA_DIGITS[n % 10] ?? "");
}
